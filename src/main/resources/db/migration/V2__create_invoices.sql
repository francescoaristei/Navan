CREATE TABLE invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    currency VARCHAR(3) NOT NULL,
    grand_total DECIMAL(19, 2) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE invoice_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL,
    transaction_id BIGINT NOT NULL,
    type VARCHAR(255) NOT NULL,
    total DECIMAL(19, 2) NOT NULL,
    metadata_snapshot TEXT NOT NULL,
    tax_lines_snapshot TEXT NOT NULL,
    fee_lines_snapshot TEXT NOT NULL,
    CONSTRAINT fk_invoice_lines_invoice
        FOREIGN KEY (invoice_id) REFERENCES invoices (id) ON DELETE CASCADE,
    CONSTRAINT fk_invoice_lines_transaction
        FOREIGN KEY (transaction_id) REFERENCES transactions (id),
    CONSTRAINT uk_invoice_lines_invoice_transaction UNIQUE (invoice_id, transaction_id),
    CONSTRAINT ck_invoice_lines_type CHECK (type IN ('FLIGHT', 'HOTEL', 'RAIL', 'NAVAN_FEE'))
);

CREATE INDEX idx_invoice_lines_transaction_id
    ON invoice_lines (transaction_id);

CREATE TABLE invoice_tax_rollup (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    rate DECIMAL(9, 6),
    amount DECIMAL(19, 2) NOT NULL,
    CONSTRAINT fk_invoice_tax_rollup_invoice
        FOREIGN KEY (invoice_id) REFERENCES invoices (id) ON DELETE CASCADE
);

CREATE INDEX idx_invoice_tax_rollup_invoice_id
    ON invoice_tax_rollup (invoice_id);

CREATE TABLE invoice_fee_rollup (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    amount DECIMAL(19, 2) NOT NULL,
    CONSTRAINT fk_invoice_fee_rollup_invoice
        FOREIGN KEY (invoice_id) REFERENCES invoices (id) ON DELETE CASCADE
);

CREATE INDEX idx_invoice_fee_rollup_invoice_id
    ON invoice_fee_rollup (invoice_id);
